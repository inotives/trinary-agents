def render(folder):
    """Validate folder and write report.html. Raises ReportError with every problem."""
    folder = Path(folder).resolve()
    problems = []
    if not folder.is_dir():
        raise ReportError([f"{folder}: not a directory"])
    report_path, plan_path, output = folder / "report.md", folder / "README.md", folder / "report.html"

    report = plan = None
    if report_path.is_file():
        report = validate_report(report_path.read_text(encoding="utf-8"), problems)
    else:
        problems.append(f"{report_path}: report.md not found")
    if plan_path.is_file():
        plan = validate_plan(plan_path.read_text(encoding="utf-8"), problems)
    else:
        problems.append(f"{plan_path}: plan README.md not found")
    if report and plan:
        report_id, plan_id = report["fields"].get("id"), plan["fields"].get("id")
        if report_id and plan_id and report_id != plan_id:
            problems.append(f"report.md: id {report_id} does not match the plan id {plan_id}")

    project_name, name_problem = find_project_name(folder)
    if name_problem:
        problems.append(name_problem)

    if output.is_symlink():
        problems.append(f"{output}: refusing to overwrite a symlink")
    elif output.exists() and MARKER not in output.read_text(encoding="utf-8", errors="replace"):
        problems.append(f"{output}: refusing to overwrite a page not generated by this renderer")

    if problems:
        raise ReportError(problems)

    page = render_html(report, plan, project_name)
    handle, temp_name = tempfile.mkstemp(prefix=".report-", suffix=".html", dir=folder)
    try:
        with os.fdopen(handle, "w", encoding="utf-8") as temp:
            temp.write(page)
        os.replace(temp_name, output)
    except BaseException:
        if os.path.exists(temp_name):
            os.unlink(temp_name)
        raise
    return output


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    if len(argv) != 1:
        print("Usage: render_report.py <RF folder>", file=sys.stderr)
        return 2
    try:
        output = render(argv[0])
    except ReportError as error:
        print(f"report rendering refused ({len(error.problems)} problem(s)); nothing was written:", file=sys.stderr)
        for problem in error.problems:
            print(f"- {problem}", file=sys.stderr)
        return 1
    except (OSError, ValueError) as error:
        print(f"report rendering failed: {error}", file=sys.stderr)
        return 1
    print(f"wrote {output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
